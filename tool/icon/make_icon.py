"""Generates the app icon sources from one set of shapes.

Outputs (relative to repo root):
  android/app/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml
  android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml
  tool/icon/build/*.svg  (rendered to PNGs by render.js)

Canvas is the 108x108 Android adaptive-icon grid; the safe zone is the
central circle of diameter 66.
"""
import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
BUILD = os.path.join(os.path.dirname(__file__), "build")

# Palette
BG_A = "#3DD9C5"   # mint (top-left)
BG_B = "#1478A8"   # ocean blue (bottom-right)
PAPER = "#FFFDF6"
FOLD = "#E9E1CF"
INK = "#1D2A44"
SOFT = "#C3CAD6"
HIGHLIGHT = "#FFC53D"  # close to the app's amber seed colour
SHADOW = "#0B4A6B"

# Card geometry (card-local units), placed centred on (54, 54)
W, H, R, F = 42.0, 50.0, 6.0, 12.0
OX, OY = 54 - W / 2, 54 - H / 2
ROT, SCALE = -8, 0.92


def card_path(dx=0.0, dy=0.0):
    x, y = OX + dx, OY + dy
    return (
        f"M{x+R:.2f},{y:.2f} H{x+W-F:.2f} L{x+W:.2f},{y+F:.2f} V{y+H-R:.2f} "
        f"A{R},{R} 0 0 1 {x+W-R:.2f},{y+H:.2f} H{x+R:.2f} "
        f"A{R},{R} 0 0 1 {x:.2f},{y+H-R:.2f} V{y+R:.2f} "
        f"A{R},{R} 0 0 1 {x+R:.2f},{y:.2f} Z"
    )


def fold_path():
    x, y = OX, OY
    return (
        f"M{x+W-F:.2f},{y:.2f} V{y+F-2.5:.2f} "
        f"A2.5,2.5 0 0 0 {x+W-F+2.5:.2f},{y+F:.2f} H{x+W:.2f} Z"
    )


def rrect(x0, y0, x1, y1, r):
    x0, x1, y0, y1 = x0 + OX, x1 + OX, y0 + OY, y1 + OY
    return (
        f"M{x0+r:.2f},{y0:.2f} H{x1-r:.2f} A{r},{r} 0 0 1 {x1:.2f},{y0+r:.2f} "
        f"V{y1-r:.2f} A{r},{r} 0 0 1 {x1-r:.2f},{y1:.2f} H{x0+r:.2f} "
        f"A{r},{r} 0 0 1 {x0:.2f},{y1-r:.2f} V{y0+r:.2f} "
        f"A{r},{r} 0 0 1 {x0+r:.2f},{y0:.2f} Z"
    )


def line(x0, x1, y):
    return f"M{OX+x0:.2f},{OY+y:.2f} H{OX+x1:.2f}"


# (path, fill, stroke, stroke_width)
HIGHLIGHT_RECT = rrect(6.0, 21.5, W - 6.5, 30.5, 2.5)
LINES = [
    (line(8.5, 25, 13.5), INK, 4.2),          # title, bold
    (line(9, W - 10, 26.0), INK, 3.0),        # highlighted line
    (line(9, W - 10, 35.5), SOFT, 3.0),
    (line(9, 24, 43.0), SOFT, 3.0),
]


def foreground_shapes(mono=False):
    shapes = []
    if mono:
        shapes.append(("stroke", card_path(), "#000000", 3.4))
        shapes.append(("fill", fold_path(), "#000000", 0))
        shapes.append(("fill", HIGHLIGHT_RECT, "#000000", 0))
        # lines: the highlighted one is cut out by drawing it in the "hole"
        for p, _c, w in LINES:
            shapes.append(("stroke", p, "#000000", w))
        return shapes
    shapes.append(("fill", card_path(1.2, 2.6), SHADOW + "@0.28", 0))
    shapes.append(("fill", card_path(), PAPER, 0))
    shapes.append(("fill", fold_path(), FOLD, 0))
    shapes.append(("fill", HIGHLIGHT_RECT, HIGHLIGHT, 0))
    for p, c, w in LINES:
        shapes.append(("stroke", p, c, w))
    return shapes


def split_color(c):
    if "@" in c:
        col, a = c.split("@")
        return col, float(a)
    return c, 1.0


# ---------- Android vector drawables ----------
def vd_path(kind, d, color, width):
    col, a = split_color(color)
    if kind == "fill":
        alpha = f'\n            android:fillAlpha="{a}"' if a != 1.0 else ""
        return (f'        <path\n            android:fillColor="{col}"{alpha}\n'
                f'            android:pathData="{d}" />')
    return (f'        <path\n            android:strokeColor="{col}"\n'
            f'            android:strokeWidth="{width}"\n'
            f'            android:strokeLineCap="round"\n'
            f'            android:strokeLineJoin="round"\n'
            f'            android:pathData="{d}" />')


def vd_foreground(mono=False):
    body = "\n".join(vd_path(*s) for s in foreground_shapes(mono))
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/icon/make_icon.py; edit that script instead. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:pivotX="54"
        android:pivotY="54"
        android:rotation="{ROT}"
        android:scaleX="{SCALE}"
        android:scaleY="{SCALE}">
{body}
    </group>
</vector>
'''


VD_BACKGROUND = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/icon/make_icon.py; edit that script instead. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="108"
                android:endY="108">
                <item android:offset="0" android:color="{BG_A}" />
                <item android:offset="1" android:color="{BG_B}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''

ADAPTIVE = '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
'''


# ---------- SVG (for PNG rendering) ----------
def svg_shapes(mono=False):
    out = []
    for kind, d, color, width in foreground_shapes(mono):
        col, a = split_color(color)
        op = f' fill-opacity="{a}"' if a != 1.0 else ""
        if kind == "fill":
            out.append(f'<path d="{d}" fill="{col}"{op}/>')
        else:
            out.append(f'<path d="{d}" fill="none" stroke="{col}" stroke-width="{width}" '
                       f'stroke-linecap="round" stroke-linejoin="round"/>')
    return "\n    ".join(out)


def svg(viewbox, clip=None, mono=False, bg=True, rounded=None):
    vb = " ".join(str(v) for v in viewbox)
    x, y, w, h = viewbox
    defs = f'''<linearGradient id="bg" x1="0" y1="0" x2="108" y2="108" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{BG_A}"/><stop offset="1" stop-color="{BG_B}"/>
    </linearGradient>'''
    clip_attr = ""
    if rounded is not None:
        defs += f'<clipPath id="c"><rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rounded}"/></clipPath>'
        clip_attr = ' clip-path="url(#c)"'
    bgrect = f'<rect x="0" y="0" width="108" height="108" fill="url(#bg)"/>' if bg else ""
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}">
  <defs>{defs}</defs>
  <g{clip_attr}>
  {bgrect}
  <g transform="translate(54 54) rotate({ROT}) scale({SCALE}) translate(-54 -54)">
    {svg_shapes(mono)}
  </g>
  </g>
</svg>
'''


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


if __name__ == "__main__":
    res = os.path.join(ROOT, "android/app/src/main/res")
    write(os.path.join(res, "drawable/ic_launcher_background.xml"), VD_BACKGROUND)
    write(os.path.join(res, "drawable/ic_launcher_foreground.xml"), vd_foreground())
    write(os.path.join(res, "drawable/ic_launcher_monochrome.xml"), vd_foreground(mono=True))
    write(os.path.join(res, "mipmap-anydpi-v26/ic_launcher.xml"), ADAPTIVE)
    # full-bleed 108 grid (Android layers / previews)
    write(os.path.join(BUILD, "full.svg"), svg((0, 0, 108, 108)))
    # tighter crop for iOS / legacy PNGs (keeps the card a natural size)
    write(os.path.join(BUILD, "square.svg"), svg((12, 12, 84, 84)))
    write(os.path.join(BUILD, "legacy.svg"), svg((12, 12, 84, 84), rounded=18))
    # macOS: rounded tile on a transparent canvas, with the standard margin
    inner = svg((12, 12, 84, 84)).replace("<svg ", '<svg x="100" y="100" width="824" height="824" ', 1)
    write(os.path.join(BUILD, "macos.svg"), f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">
  <defs>
    <clipPath id="tile"><rect x="100" y="100" width="824" height="824" rx="185"/></clipPath>
    <filter id="sh" x="-20%" y="-20%" width="140%" height="140%"><feDropShadow dx="0" dy="10" stdDeviation="12" flood-opacity="0.3"/></filter>
  </defs>
  <rect x="100" y="100" width="824" height="824" rx="185" fill="#1478A8" filter="url(#sh)"/>
  <g clip-path="url(#tile)">{inner}</g>
</svg>
''')
    write(os.path.join(BUILD, "mono.svg"), svg((0, 0, 108, 108), mono=True, bg=False))
    print("ok")
